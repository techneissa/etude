// The usage line of each mode, and the song options.
void print_usage_synopsis() {
    std::printf(
        "usage: etude [--startup-log] [--song FILE] [--mode flow|wait] [--hands "
        "both|left|right]\n"
        "               [--song-sound mute|other-hand|both-hands] [--play] [--seek S]\n"
        "               [--midi-log | --latency-log] [--style STYLE]\n"
        "               [--colors SCHEME] [--names MODE] [--octaves NUMBERING] [--window WxH]\n"
        "               [--panel-mm WxH]\n"
        "               [--key-size SIZE] [--renderer basic|gpu|gl] [--hit-effect EFFECT]\n"
        "               [--show-typing-keys]\n"
        "               [--settings-dir DIR] [--crash-screen]\n"
        "               [--debug-effects] [--sound-font SF2] [--audio-latency-log]\n"
        "               [--input midi|mic|both] [--mic-wav FILE] [--mic-log] [--frame-log]\n"
        "       etude --synth-test [--audio-latency-log] [--sound-font SF2]\n"
        "       etude --song-timing synth|midi [--song FILE] [--song-lead-ms N]\n"
        "               [--dev-frame-jitter-ms N] [--timing-seconds S] [--timing-direct]\n"
        "       etude --version\n"
        "       etude --bench-search [--songs N]\n"
        "       etude --bench-scan DIR\n"
        "       etude --bench-spikes [--spike-notes N]\n"
        "       etude --bench-hand-memory [--spike-notes N]\n"
        "       etude --bench | --bench-all [--style STYLE] [--notes N] [--seconds S]\n"
        "               [--size WxH | --window WxH] [--no-degrade] [--bar SONG]\n"
        "               [--screenshot PNG [--at S | --shot-pattern run|chord|song-*|all\n"
        "               [--shot-after-ms N]]]\n"
        "  --song FILE    open a song: .mid, .musicxml/.xml, .mxl, .mscz or .abc (FILE.abc#X=3\n"
        "                 is tune 3 of a file with several). Without it the last session's\n"
        "                 song comes back, paused where you left it (--song none counts as\n"
        "                 no --song, to undo an earlier one)\n"
        "  --mode MODE    flow (the song keeps going, each note graded) or wait (the song\n"
        "                 waits at each chord until you play it)\n"
        "  --hands HANDS  the hands you practise: both, left or right\n"
        "  --song-sound S what you hear of the song: mute (default), other-hand, both-hands\n"
        "  --play         start playing the song at once\n"
        "  --metronome on|off  the metronome for this run\n"
        "  --count-in N   bars of count-in (0, 1 or 2) for this run\n"
        "  --speed P      the song's speed in percent (25..200) for this run\n"
        "  --seek S       start the song S seconds in\n");
}

