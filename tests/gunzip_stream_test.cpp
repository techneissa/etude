std::vector<std::uint8_t> repeating() {
    std::vector<std::uint8_t> head;
    for (int i = 0; i < 1000; ++i) {
        head.push_back(static_cast<std::uint8_t>((i * 7 + 3) % 251));
    }
    std::vector<std::uint8_t> data = head;
    data.insert(data.end(), 200000, 'a');
    data.insert(data.end(), head.begin(), head.end());
    for (int i = 0; i < 5000; ++i) {
        data.push_back(static_cast<std::uint8_t>((i * 13) % 256));
    }
    return data;
}

std::uint32_t crc32_of(const std::vector<std::uint8_t>& data) {
    std::uint32_t crc = 0xFFFFFFFFu;
    for (const std::uint8_t b : data) {
        crc ^= b;
        for (int k = 0; k < 8; ++k) {
            crc = (crc >> 1) ^ (0xEDB88320u & (0u - (crc & 1u)));
        }
    }
    return ~crc;
}

// A gzip member made of stored (not compressed) blocks: any size, no compressor needed.
std::vector<std::uint8_t> stored_gzip(const std::vector<std::uint8_t>& data) {
    std::vector<std::uint8_t> gz{0x1f, 0x8b, 8, 0, 0, 0, 0, 0, 0, 0xff};
    std::size_t at = 0;
    do {
        const std::size_t n = std::min<std::size_t>(65535, data.size() - at);
        const bool last = at + n == data.size();
        gz.push_back(last ? 1 : 0);
        gz.push_back(static_cast<std::uint8_t>(n & 0xff));
        gz.push_back(static_cast<std::uint8_t>(n >> 8));
        gz.push_back(static_cast<std::uint8_t>(~n & 0xff));
        gz.push_back(static_cast<std::uint8_t>((~n >> 8) & 0xff));
        gz.insert(gz.end(), data.begin() + static_cast<std::ptrdiff_t>(at),
                  data.begin() + static_cast<std::ptrdiff_t>(at + n));
        at += n;
    } while (at < data.size());
    const std::uint32_t crc = crc32_of(data);
    const auto size = static_cast<std::uint32_t>(data.size());
    for (const std::uint32_t word : {crc, size}) {
        for (int k = 0; k < 4; ++k) {
            gz.push_back(static_cast<std::uint8_t>(word >> (8 * k)));
        }
    }
    return gz;
}

struct Run {
    GunzipError error = GunzipError::None;
    std::vector<std::uint8_t> out;
    std::size_t largest_piece = 0;
    std::size_t largest_read = 0;

    bool ok() const { return error == GunzipError::None; }
};

// Runs gunzip_stream over `gz`, handing out at most `piece` input bytes per read.
Run run(const std::vector<std::uint8_t>& gz, std::size_t piece, std::uint64_t max_bytes = 1ULL << 30) {
    Run r;
    std::size_t at = 0;
    r.error = gunzip_stream(
        [&](std::span<std::uint8_t> into) -> std::ptrdiff_t {
            const std::size_t n = std::min({piece, into.size(), gz.size() - at});
            std::copy_n(gz.begin() + static_cast<std::ptrdiff_t>(at), n, into.begin());
            at += n;
            r.largest_read = std::max(r.largest_read, into.size());
            return static_cast<std::ptrdiff_t>(n);
        },
        [&](std::span<const std::uint8_t> out) {
            r.largest_piece = std::max(r.largest_piece, out.size());
            r.out.insert(r.out.end(), out.begin(), out.end());
            return true;
        },
        max_bytes);
    return r;
}

std::string text(const Run& r) { return std::string(r.out.begin(), r.out.end()); }

